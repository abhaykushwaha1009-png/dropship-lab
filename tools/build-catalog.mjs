// Generates site/assets/catalog.js from the shop data so cart/checkout can price
// every SKU client-side without a JSON fetch (file:// safe, CSP safe).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(resolve(root, 'docs/_data/shops.json'), 'utf8'));

const catalog = {};
const shops = {};
for (const shop of data.shops) {
  shops[shop.slug] = { name: shop.name, floor: shop.priceFloor };
  for (const p of shop.products) {
    catalog[p.id] = { name: p.name, price: p.price, shop: shop.slug, shopName: shop.name };
  }
  // the bundle SKU each hero button sells
  catalog[`${shop.slug}-kit`] = {
    name: `${shop.name} — full kit`,
    price: shop.priceFloor,
    shop: shop.slug,
    shopName: shop.name,
    kit: true,
  };
}

// hand-authored shops that predate shops.json
const extra = JSON.parse(readFileSync(resolve(root, 'site/_data/catalog-extra.json'), 'utf8'));
for (const shop of extra.shops) {
  shops[shop.slug] = { name: shop.name, floor: shop.kitPrice };
  for (const p of shop.products) {
    catalog[p.id] = { name: p.name, price: p.price, shop: shop.slug, shopName: shop.name };
  }
  catalog[shop.kitId] = {
    name: shop.kitName,
    price: shop.kitPrice,
    shop: shop.slug,
    shopName: shop.name,
    kit: true,
  };
}

const out = `// Generated by tools/build-catalog.mjs — do not edit by hand.
window.CATALOG = ${JSON.stringify(catalog, null, 0)};
window.SHOPS = ${JSON.stringify(shops, null, 0)};
`;
mkdirSync(resolve(root, 'site/assets'), { recursive: true });
writeFileSync(resolve(root, 'site/assets/catalog.js'), out);
console.log(`catalog: ${Object.keys(catalog).length} SKUs, ${Object.keys(shops).length} shops`);
